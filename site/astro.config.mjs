import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import sitemap from '@astrojs/sitemap';
import { satteri } from '@astrojs/markdown-satteri';
import { rewriteMdLinks } from './src/plugins/rewrite-md-links.mjs';

export default defineConfig({
  site: 'https://digiwomb-dev.github.io/UnboundAir/',
  // Project Pages serve below a subpath, so every local URL needs the base.
  // If hosting ever moves to a host root (custom domain, organisation pages
  // repository), this line goes away together with the subpath in `site`.
  base: '/UnboundAir/',
  // The site root carries no page of its own, so it points at the default
  // locale's landing page (English is the main language). The former
  // `/de/` and `/en/` entries are gone: both locale roots now have a real
  // index page (DO-17), and an Astro redirect loses to a real page at the
  // same path anyway — keeping them would be dead configuration that reads
  // like intent.
  redirects: {
    '/': '/UnboundAir/en/',
  },
  // Consciously off (condition 7 in #229): no speculative requests of any
  // kind until the DS-01 gate (#233) watches every deploy.
  prefetch: false,
  // DS-03: the texts keep relative `.md` links, because the DO-15
  // link-target rule forbids per-locale absolute URLs and GitHub readers
  // need the relative form. The build makes them work — reasoning and the
  // three cases are in src/plugins/rewrite-md-links.mjs.
  //
  // Named explicitly as `processor: satteri(...)` rather than through
  // `markdown.remarkPlugins`: that option runs on the unified processor,
  // which Astro 7 no longer installs (Sätteri is the default). Using it
  // would mean adding @astrojs/markdown-remark to run the pipeline a second
  // way. Sätteri is already the processor this site builds with — passing
  // it a plugin keeps one pipeline.
  markdown: {
    processor: satteri({ mdastPlugins: [rewriteMdLinks] }),
  },
  integrations: [
    starlight({
      title: 'UnboundAir',
      // Main language first: English is the default locale, so English URLs
      // carry no prefix and missing German translations would fall back to
      // English with a marker. With German-only content (until DO-16 fills
      // docs/en/) the English locale is empty by consequence, not by defect —
      // decided in #229 ("Sofort en"), the fallback check moves to #232.
      defaultLocale: 'en',
      locales: {
        en: { label: 'English', lang: 'en' },
        de: { label: 'Deutsch', lang: 'de' },
      },
      // Four groups instead of the autogenerated list (DO-17). Autogeneration
      // sorts alphabetically, which met the reader with Configuration before
      // the guide that needs it and put the contributor page in the middle of
      // the user documentation; nothing expressed what kind of page each one
      // was.
      //
      // The grouping lives here rather than in folders because the layout of
      // `docs/` is fixed and Starlight pairs translations by filename — which
      // page belongs in which group is a presentation decision and belongs in
      // the presentation layer. One config serves both locales: `translations`
      // carries the German labels, and Starlight picks by language.
      //
      // `legal-notice` and `privacy` are deliberately absent. They carry
      // `sidebar.hidden` from DS-02 and hang in the footer; naming them here
      // would undo that.
      sidebar: [
        {
          label: 'Start',
          translations: { de: 'Start' },
          items: ['index', 'quickstart'],
        },
        {
          label: 'Guides',
          translations: { de: 'Anleitungen' },
          items: ['operations', 'output-modules', 'troubleshooting'],
        },
        {
          label: 'Reference',
          translations: { de: 'Referenz' },
          items: ['configuration', 'cli', 'protocol', 'hardware'],
        },
        {
          label: 'Contributing',
          translations: { de: 'Mitmachen' },
          items: ['development'],
        },
      ],
      // No global `head` entries — condition 2 in #229. This object-level
      // `head` would apply to every page and is the hook Starlight's own
      // docs use to load analytics from a CDN. Per-page `head` frontmatter
      // stays allowed for tags that load nothing (e.g. `meta robots`).
      // The CSP lives in src/components/Head.astro instead.
      head: [],
      // No "Built with Starlight" credit line; social links only to the
      // project's own repository (condition 8 in #229).
      credits: false,
      social: [
        {
          icon: 'github',
          label: 'GitHub',
          href: 'https://github.com/digiwomb-dev/UnboundAir',
        },
      ],
      // The "edit this page" URL is computed in
      // src/components/EditLink.astro instead of `editLink.baseUrl`:
      // Starlight would append the path below the site directory
      // (`src/content/docs/…`), which does not exist in the repository.
      components: {
        Footer: './src/components/Footer.astro',
        EditLink: './src/components/EditLink.astro',
        Head: './src/components/Head.astro',
      },
    }),
    sitemap({
      // The legal notice (#234, DS-02) carries noindex and must not be
      // listed: slug `legal-notice` in every locale. #234 conforms to this.
      filter: (page) => !page.includes('/legal-notice/'),
    }),
  ],
});
